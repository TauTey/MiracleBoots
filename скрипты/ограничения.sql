-- =====================================================
-- 1. ОГРАНИЧЕНИЕ UNIQUE (уникальность)
-- Налоговый номер организации должен быть уникальным
-- =====================================================
ALTER TABLE [dbo].[Торговая организация]
ADD CONSTRAINT UQ_Торговая_организация_Налоговый_номер UNIQUE ([Налоговый_номер]);
GO

-- =====================================================
-- 2. ОГРАНИЧЕНИЕ CHECK (проверка допустимых значений)
-- Тип торговой точки может быть только: 'универмаг', 'магазин', 'киоск', 'лоток'
-- =====================================================
ALTER TABLE [dbo].[Торговая точка]
ADD CONSTRAINT CHK_Торговая_точка_Тип CHECK ([Тип] IN ('универмаг', 'магазин', 'киоск', 'лоток'));
GO

-- =====================================================
-- 3. ОГРАНИЧЕНИЕ DEFAULT (значение по умолчанию)
-- Для новых заказов дата заказа по умолчанию - текущая дата
-- =====================================================
ALTER TABLE [dbo].[Заказы поставщикам]
ADD CONSTRAINT DF_Заказы_поставщикам_Дата_заказа DEFAULT (GETDATE()) FOR [Дата_заказа];
GO

