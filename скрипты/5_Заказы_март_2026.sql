USE [Торговая организация]
GO

CREATE VIEW Заказы_март_2026 AS
SELECT 
    z.ID AS Номер_заказа,
    z.Дата_заказа,
    z.Название_товара,
    z.Количество,
    z.Цена,
    t.Тип AS Тип_точки,
    t.Адрес AS Адрес_точки,
    p.Название AS Поставщик
FROM [dbo].[Заказы поставщикам] z
INNER JOIN [dbo].[Торговая точка] t ON z.ID_торговой_точки = t.ID
INNER JOIN [dbo].[Поставщики] p ON z.ID_поставщика = p.ID
WHERE z.Дата_заказа BETWEEN '2026-03-01' AND '2026-03-31'
GO