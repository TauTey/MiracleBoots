USE [Торговая организация]
GO
SELECT z.ID AS Номер_заказа, z.Дата_заказа, z.Название_товара,
       t.Тип AS Тип_точки, p.Название AS Поставщик
FROM [dbo].[Заказы поставщикам] z
INNER JOIN [dbo].[Торговая точка] t ON z.ID_торговой_точки = t.ID
INNER JOIN [dbo].[Поставщики] p ON z.ID_поставщика = p.ID
WHERE t.Тип = N'магазин'
GO