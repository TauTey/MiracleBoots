USE [Торговая организация]
GO
UPDATE [dbo].[Заказы поставщикам]
SET Цена = Цена * 1.15
WHERE ID_поставщика = (SELECT ID FROM [dbo].[Поставщики] WHERE Название = N'ООО "ПродуктОпт"')
GO
-- Проверка обновления
SELECT z.ID, z.Название_товара, z.Цена, p.Название AS Поставщик
FROM [dbo].[Заказы поставщикам] z
INNER JOIN [dbo].[Поставщики] p ON z.ID_поставщика = p.ID
WHERE p.Название = N'ООО "ПродуктОпт"'
GO