USE [Торговая организация]
GO
SELECT 
    ID AS Номер_заказа,
    Дата_заказа,
    YEAR(Дата_заказа) AS Год,
    MONTH(Дата_заказа) AS Месяц,
    DAY(Дата_заказа) AS День,
    DATENAME(weekday, Дата_заказа) AS День_недели
FROM [dbo].[Заказы поставщикам]
WHERE Дата_заказа BETWEEN '2026-03-01' AND '2026-03-31'
ORDER BY Дата_заказа
GO