GO
UPDATE [dbo].[Заказы поставщикам]
SET Цена = Цена * 1.1
WHERE Дата_заказа BETWEEN '2026-03-01' AND '2026-03-31'
GO
-- Проверка обновления (вывод первых 5 обновлённых заказов)
SELECT TOP 5 ID, Дата_заказа, Цена
FROM [dbo].[Заказы поставщикам]
WHERE Дата_заказа BETWEEN '2026-03-01' AND '2026-03-31'
ORDER BY ID
GO