USE [Торговая организация]
GO
CREATE VIEW Информация_о_продавцах AS
SELECT 
    p.ID AS Код_продавца,
    p.Фамилия,
    p.Имя,
    p.Отчество,
    p.Должность,
    p.Год_рождения,
    p.Пол,
    t.Тип AS Тип_точки,
    t.Адрес AS Адрес_точки,
    t.ФИО_заведующего
FROM [dbo].[Продавцы] p
INNER JOIN [dbo].[Торговая точка] t ON p.ID_торговой_точки = t.ID
GO